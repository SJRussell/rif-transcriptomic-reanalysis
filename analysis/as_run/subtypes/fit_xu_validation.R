.libPaths(c('<r_library>',.libPaths()))
suppressPackageStartupMessages({library(edgeR);library(limma);library(jsonlite)})
BASE<-'<workspace>/subtypes_2026-09-08';ROOT<-file.path(BASE,'corrected_baseline');RAW<-file.path(BASE,'nibi_results')
qc<-read.csv(file.path(RAW,'Xu2026_sample_qc.csv'));stopifnot(nrow(qc)==22,!anyDuplicated(qc$sample))
qc$forward_fraction<-qc$assigned_forward/(qc$assigned_forward+qc$assigned_reverse)
stopifnot(all(is.finite(qc$forward_fraction)))
strand<-if(all(qc$forward_fraction>=.8))'forward' else if(all(qc$forward_fraction<=.2))'reverse' else 'unstranded'
qc$selected_counts<-strand;qc$technical_flag<-qc$retained_reads<1e6|as.numeric(sub('%','',qc$unique_alignment))<50
write.csv(qc,file.path(BASE,'audit/Xu2026_strand_and_sample_qc.csv'),row.names=FALSE)
if(any(qc$technical_flag))stop('Technical QC flags require investigation before clinical analysis; no samples excluded.')
d<-read.csv(gzfile(file.path(RAW,paste0('Xu2026_',strand,'_counts.csv.gz'))),check.names=FALSE)
ids<-sub('[.][0-9]+$','',d[[1]]);hg<-read.delim(file.path(ROOT,'inputs/hgnc_complete_set.txt'),quote='',colClasses='character',na.strings='')
hg<-hg[hg$status=='Approved'&!is.na(hg$ensembl_gene_id),]
unambig<-!duplicated(hg$ensembl_gene_id)&!duplicated(hg$ensembl_gene_id,fromLast=TRUE)
hg<-hg[unambig,];symbols<-hg$symbol[match(ids,hg$ensembl_gene_id)];good<-!is.na(symbols)
write.csv(data.frame(EnsemblID=d[[1]],lookup_id=ids,approved_symbol=symbols,retained=good),file.path(BASE,'audit/Xu2026_gene_mapping.csv'),row.names=FALSE)
m<-rowsum(as.matrix(d[good,-1,drop=FALSE]),group=symbols[good],reorder=TRUE)
stopifnot(!anyDuplicated(rownames(m)),all(m>=0),all(m==round(m)))
md<-fromJSON(file.path(BASE,'reference/Xu2026/sample_metadata.json'));md<-md[match(colnames(m),md$title),]
stopifnot(!anyNA(md$title),identical(md$title,colnames(m)))
sm<-data.frame(study='Xu2026',sample=md$title,condition=ifelse(startsWith(md$title,'RIF'),'RIF','Control'),arm='rnaseq',tech='bulk',run=md$run_accession,age=as.numeric(md$age),collection_date=md$collection_date,timing='HRT P+5 per paper; deposit provenance unresolved',role='repository_linked_validation_provenance_unresolved')
stopifnot(sum(sm$condition=='RIF')==9,sum(sm$condition=='Control')==13,!anyNA(sm$age))
parsed<-parse(file.path(ROOT,'scripts/fit_studies.R'))
for(e in parsed)if(is.call(e)&&identical(e[[1]],as.name('<-'))&&identical(e[[2]],as.name('fit_one')))eval(e)
fit_one('Xu2026',m,sm,TRUE,label='Xu2026_external')
fit_one('Xu2026',m,sm,TRUE,label='Xu2026_external_age',covariates=cbind(age=sm$age-mean(sm$age)))
write.csv(sm,file.path(BASE,'audit/Xu2026_final_metadata.csv'),row.names=FALSE)
write_json(list(count_direction=strand,n_control=13,n_rif=9,genes_mapped=nrow(m),primary='RIF versus control',sensitivity='age adjusted',raw_rules='reference/Xu2026/RAW_VALIDATION_RULES.md'),file.path(BASE,'audit/Xu2026_fit_summary.json'),pretty=TRUE,auto_unbox=TRUE)
cat('XU_VALIDATION_FIT_COMPLETE',strand,'\n')
